#!/usr/bin/env node
/**
 * Deterministic generator: validated snapshot (+ reviews) -> the gated catalogue entries.
 *
 * Contents are ONLY fields that passed the validator, or an explicit null where no source exists. It never
 * writes text of its own: the caution is the REVIEWED text or null (the draft's unreviewed line is dropped),
 * and identification features, lookalikes, habitat and sprite are null because the draft has none.
 * Same bytes on every machine: sorted keys, no clock, no random, no float, no path or host dependence
 * (the same reproducibility rule as structures.tsx).
 *
 *   node scripts/expansion/generate_pilot.mjs [--out FILE] [--check]
 * Default --out is src/data/expansion-pilot.generated.json, which is human-owned (tier 0): the OWNER runs it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { ROOT, canonicalJson, isRealCitation, loadIntegration, loadReviews, loadSnapshot, publicationGate, validateBatch } from './validate_record.mjs';

export const GENERATED = 'src/data/expansion-pilot.generated.json';
export const REVIEW_COPY = 'docs/expansion/pilot/expansion-pilot.generated.json';
export const FLAG = 'NEXT_PUBLIC_EXPANSION_PILOT';
const DRAFT_SOURCE = 'owner-supplied master sheet (draft), not independently verified';

const asset = (a, approved) => a ? { approved, origin: a.origin, botanicalReviewRequired: a.botanicalReviewRequired, sha256: a.recordedSha256 } : null;

export function generate(snapshot = loadSnapshot(), reviews = loadReviews(), integ = loadIntegration()) {
  const results = validateBatch(snapshot, reviews, integ);
  const bad = results.flatMap((r) => r.errors.map((e) => `#${r.cardNumber} ${r.id}: ${e.code} ${e.message}`));
  if (bad.length) throw new Error(`refusing to generate from invalid records:\n${bad.join('\n')}`);
  const cards = snapshot.cards.map((entry) => {
    const r = entry.record, gate = publicationGate(entry, reviews[r.id]), rv = reviews[r.id]?.caution;
    const sourced = gate.reasons.every((x) => !/^caution_/.test(x.code)) && rv;
    return {
      id: r.id, cardNumber: r.cardNumber, commonName: r.commonName, scientificName: r.scientificName,
      identity: { level: 'species' },
      collectionId: null,
      deck: { rarity: r.front.rarity, xp: r.front.xp, season: r.front.season, uses: r.front.uses, stats: r.front.stats },
      back: Object.fromEntries(Object.entries(r.back).map(([k, v]) => [k, { values: v, reviewed: false, source: DRAFT_SOURCE }])),
      caution: sourced ? { text: rv.text, sources: rv.sources, reviewedBy: rv.reviewedBy, reviewedAt: rv.reviewedAt } : null,
      citations: (r.researchLinks?.links ?? []).filter(isRealCitation).map((l) => l.url),
      identification: null, lookalikes: null, habitat: null, sprite: null,
      assets: {
        main: asset(entry.assets.main, entry.inventory.mainImage === 'APPROVED'),
        pixel: asset(entry.assets.pixel, entry.inventory.pixelIcon === 'APPROVED'),
        tall: asset(entry.assets.tall, entry.inventory.tallPreview === 'APPROVED'),
        publishedPath: null,
      },
      publication: gate,
    };
  }).sort((a, b) => a.cardNumber - b.cardNumber);
  return canonicalJson({
    $comment: `GENERATED by scripts/expansion/generate_pilot.mjs. Never hand-edit. Gated and OFF: no live module imports this file; ${FLAG} must be 'on' at build time and nothing reads it yet.`,
    schemaVersion: 1, flag: FLAG,
    source: { draftCommit: snapshot.snapshotOf.draftCommit, draftFileSha256: snapshot.snapshotOf.draftFileSha256, files: snapshot.sourceFiles.map((f) => ({ file: f.file, sha256: f.recordedSha256 })) },
    cards,
  });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? process.argv[i + 1] : GENERATED;
  const text = generate();
  if (process.argv.includes('--check')) {
    const same = existsSync(join(ROOT, out)) && readFileSync(join(ROOT, out), 'utf8') === text;
    console.log(same ? `${out} is up to date` : `${out} is STALE: re-run without --check`);
    process.exit(same ? 0 : 1);
  }
  mkdirSync(dirname(join(ROOT, out)), { recursive: true });
  writeFileSync(join(ROOT, out), text);
  console.log(`wrote ${out}`);
}
