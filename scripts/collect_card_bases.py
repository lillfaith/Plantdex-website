#!/usr/bin/env python3
"""Gather every art-less card base into expansion/card-bases/ (one flat folder).

A card counts as art-less when its package has no approved artwork on disk
(profile-draft.json "artwork_on_disk" has no supplied file). Safe to re-run: the folder is
rebuilt from expansion/cards/, which stays the source of truth.
"""
import json, shutil, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "expansion/cards", ROOT / "expansion/card-bases"
data = {c["cardNumber"]: c for c in json.load(open(ROOT / "src/data/expansion-cards.json"))["cards"]}
if OUT.exists():
    shutil.rmtree(OUT)
OUT.mkdir(parents=True)
rows = []
for d in sorted(SRC.iterdir()):
    if not d.is_dir():
        continue
    prof = json.load(open(d / "profile-draft.json"))
    art = prof.get("artwork_on_disk") or {}
    if any(v and v != "NOT YET SUPPLIED" for v in art.values()):
        continue
    n = int(d.name.split("_")[0]); slug = d.name.split("_", 1)[1]
    pdf = next(d.glob("*.pdf"))
    for src, name in ((d / "front.png", "front.png"), (d / "back.png", "back.png"), (pdf, "card.pdf")):
        shutil.copy2(src, OUT / f"{n:03d}_{slug}_{name}")
    c = data[n]
    rows.append((n, c["commonName"], c["front"]["rarity"], slug))
lines = ["# Art-less card bases", "",
         "Generated by `scripts/collect_card_bases.py` from `expansion/cards/` (the source of truth).",
         "Cards with approved artwork (#57-61) are not listed. Hidden drafts: not promoted, not on the site.", "",
         "| # | Card | Rarity | Files |", "|---|---|---|---|"]
for n, name, r, slug in rows:
    p = f"{n:03d}_{slug}"
    lines.append(f"| {n} | {name} | {r} | `{p}_front.png`, `{p}_back.png`, `{p}_card.pdf` |")
lines += ["", f"{len(rows)} cards."]
(OUT / "INDEX.md").write_text("\n".join(lines) + "\n")
print(len(rows), "cards ->", OUT)
