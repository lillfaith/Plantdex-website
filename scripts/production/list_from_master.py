#!/usr/bin/env python3
"""Build the production species list from the corrected expansion master.

    python3 scripts/production/list_from_master.py --master PlantDex_85_All_Requested_Corrections.json \\
        --out evidence/production/species-85.json

The master is the SAME canonical file the site-side import uses (`expansion/source/` on the
development branch), so card numbers cannot drift between the two. Only what the photo queue needs
is copied: number, names, the master's region codes, and the safety-review flag.

THE SAFETY FLAG is the six species the owner named earlier as needing safety review before any
preparation is shown; they are matched by SCIENTIFIC NAME (their numbers changed when Blue
Mistflower was removed) and the batch picker runs them last. It affects ordering only. It decides
nothing about the cards.

`approved: true` records the owner's instruction to use this master as the production list; it is
not a botanical or safety approval of any card.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

SAFETY_FLAGGED = {
    "Frangula purshiana": "Cascara",
    "Scrophularia californica": "California Figwort",
    "Condea emoryi": "Desert Lavender",
    "Ephedra trifurca": "Mormon Tea",
    "Bacopa monnieri": "Water Hyssop (Brahmi)",
    "Rhododendron groenlandicum": "Bog Labrador Tea",
}


def build(master_path: pathlib.Path) -> dict:
    raw = pathlib.Path(master_path).read_bytes()
    m = json.loads(raw)
    cards = m["cards"]
    errors = []
    lo, hi = m["cardNumberRange"]
    if [c["cardNumber"] for c in cards] != list(range(lo, hi + 1)) or m["cardCount"] != len(cards):
        errors.append("the master's card numbers/count are not an unbroken run matching its header")
    names = {c["scientificName"] for c in cards}
    if "Conoclinium coelestinum" in names:
        errors.append("Blue Mistflower is present in the master")
    missing = [s for s in SAFETY_FLAGGED if s not in names]
    if missing:
        errors.append(f"safety-flagged species not in the master: {missing}")
    if errors:
        raise SystemExit("REFUSED:\n  - " + "\n  - ".join(errors))
    return {
        "_what": "Production photo queue list. GENERATED by scripts/production/list_from_master.py; do not hand-edit.",
        "approved": True,
        "approved_by": "owner, by instruction to use the corrected master as the production list (2026-11-17)",
        "count": len(cards),
        "note": "`approved` means 'use this as the queue', not that any card's botany or safety copy is approved.",
        "source": {"file": "PlantDex_85_All_Requested_Corrections.json", "sha256": hashlib.sha256(raw).hexdigest(),
                   "schemaVersion": m["schemaVersion"], "status": m["status"]},
        "species": [{"card": c["cardNumber"], "common": c["name"], "scientific": c["scientificName"],
                     "regions": c["regions"], "safety_flag": c["scientificName"] in SAFETY_FLAGGED} for c in cards],
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--master", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    data = build(pathlib.Path(a.master))
    pathlib.Path(a.out).write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {a.out}: {data['count']} cards, #{data['species'][0]['card']}-#{data['species'][-1]['card']}, "
          f"{sum(s['safety_flag'] for s in data['species'])} safety-flagged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
